import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:3000';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
await p.goto(BASE + '/registro', { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
await p.fill('input[type="text"]', 'QA Tester');
await p.fill('input[type="email"]', `qa.${Date.now()}@local.test`);
await p.fill('input[type="password"]', 'QaTest2026!');
await p.click('button[type="submit"]');
await p.waitForTimeout(5000);
console.log('URL:', p.url().replace(BASE, ''));
console.log('BODY:', (await p.locator('body').innerText()).replace(/\n+/g, ' | ').slice(0, 250));
await b.close();
